-- Описание по названию подвески. Возвращает { guide, kind, targets, text } или nil.
function WI.Describe( name )
	if not name then return end

	for _, e in ipairs( WI.List ) do
		local caps = { string.find( name, e[1] ) }

		if caps[1] then
			local cap = caps[3]
			local kind = e.kind

			if isfunction( kind ) then
				kind = kind( name, cap )
			elseif cap then
				kind = string.format( kind, cap )
			end

			local text = e.text

			for _, m in ipairs( WI.Modifiers ) do
				if string.find( name, m[1], 1, true ) then text = text .. " " .. m[2] end
			end

			local count = string.match( name, "×(%d+)" )

			if count then kind = kind .. ", " .. count .. " шт." end

			return { guide = e.guide, kind = kind, targets = e.targets, text = text }
		end
	end
end
